        "(?<![а-яёА-ЯЁ])(является|очень|также|только|просто|уже|ещё|еще|этот|эта|это|эти|ваш[а-яё]*|свой|своя|своё|свои)(?![а-яёА-ЯЁ])",
        RegexOption.IGNORE_CASE
    )

    private const val VOWELS = "аеёиоуыэюяАЕЁИОУЫЭЮЯ"

    fun apply(text: String, maxWordLen: Int = 9): String {
        var s = text
        for ((re, rep) in dict) s = re.replace(s, rep)
        s = filler.replace(s, "")
        s = s.replace(Regex("\\s+"), " ")
            .replace(Regex(" ([,.!?:;])"), "$1")
            .trim()
        // длинные слова режем после согласной: «интересный» → «интерес.»
        s = Regex("[а-яёА-ЯЁ]{${maxWordLen + 2},}").replace(s) { m -> cutWord(m.value, maxWordLen) }
        return s.replaceFirstChar { it.uppercaseChar() }
    }

    private fun cutWord(w: String, maxLen: Int): String {
        var end = maxLen.coerceAtMost(w.length - 1)
        // режем так, чтобы последняя буква была согласной — так читается легче
        while (end > 4 && VOWELS.indexOf(w[end - 1]) >= 0) end--
        return w.substring(0, end) + "."
    }
